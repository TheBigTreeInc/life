from playwright.sync_api import sync_playwright
from pathlib import Path
html=(Path(__file__).resolve().parent.parent/'PLAY.html').read_text()
with sync_playwright() as p:
 b=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 for width,height in [(320,568),(390,844),(768,1024),(1440,900),(1920,1080)]:
  page=b.new_page(viewport={'width':width,'height':height})
  page.set_default_timeout(6000)
  errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  page.set_content(html,wait_until='load')
  page.locator('#startNewGameBtn').click()
  page.locator('[data-travel="agency"]').click()
  page.locator('#venueLayer').wait_for(state='visible',timeout=3000)
  assert page.locator('#classicEmployerFilter').is_visible(),(width,'no employer selector')
  page.locator('#classicEmployerFilter').select_option('Monolith Burgers')
  assert page.locator('#classicEmployerFilter option:checked').inner_text().startswith('Monolith Burger'),(width,'wrong employer label')
  cook=page.locator('[data-act="apply:classic-monolith-cook"]')
  assert cook.is_visible(),(width,'cook job not visible')
  cook.click()
  page.wait_for_timeout(85)
  assert page.locator('.profile-job').inner_text().find('Monolith Burger')>=0,(width,page.locator('.profile-job').inner_text())
  assert page.locator('[data-travel="diner"]').get_attribute('class').find('is-workplace')>=0,(width,'workplace marker absent')
  assert page.locator('[data-travel="market"]').get_attribute('class').find('is-workplace')<0,(width,'wrong workplace highlighted')
  page.locator('#venueDone').click()
  page.locator('[data-travel="diner"]').click()
  page.locator('#venueLayer').wait_for(state='visible',timeout=3000)
  work=page.locator('[data-act="work"]');assert work.is_visible(),(width,'no work action at diner')
  assert 'Monolith Burger' in work.inner_text(),(width,work.inner_text())
  box=page.evaluate('({scrollH:document.documentElement.scrollHeight,height:document.documentElement.clientHeight,scrollW:document.documentElement.scrollWidth,width:document.documentElement.clientWidth})')
  assert box['scrollH']<=box['height']+1 and box['scrollW']<=box['width']+1,(width,box)
  assert not errors,(width,errors)
  print('OK',width,height,'profile',page.locator('.profile-job').inner_text(),'scroll',box)
  page.close()
 b.close()
